import logging
import os

import numpy as np
import torch


class AverageMeter:
    def __init__(self, length=0):
        self.length = length
        self.reset()

    def reset(self):
        if self.length > 0:
            self.history = []
        else:
            self.count = 0
            self.sum = 0.0
        self.val = 0.0
        self.avg = 0.0

    def update(self, val, num=1):
        if self.length > 0:
            assert num == 1
            self.history.append(val)
            if len(self.history) > self.length:
                del self.history[0]
            self.val = self.history[-1]
            self.avg = np.mean(self.history)
        else:
            self.val = val
            self.sum += val * num
            self.count += num
            self.avg = self.sum / self.count


def intersectionAndUnion(output, target, K, ignore_index=255):
    assert output.ndim in [1, 2, 3]
    assert output.shape == target.shape
    output = output.reshape(output.size).copy()
    target = target.reshape(target.size)
    output[np.where(target == ignore_index)[0]] = ignore_index
    intersection = output[np.where(output == target)[0]]
    area_intersection, _ = np.histogram(intersection, bins=np.arange(K + 1))
    area_output, _ = np.histogram(output, bins=np.arange(K + 1))
    area_target, _ = np.histogram(target, bins=np.arange(K + 1))
    area_union = area_output + area_target - area_intersection
    return area_intersection, area_union, area_target


def count_params(model):
    return sum(p.numel() for p in model.parameters()) / 1e6


logs = set()


def init_log(name, level=logging.INFO):
    if (name, level) in logs:
        return
    logs.add((name, level))
    logger = logging.getLogger(name)
    logger.setLevel(level)
    ch = logging.StreamHandler()
    ch.setLevel(level)
    if "SLURM_PROCID" in os.environ:
        rank = int(os.environ["SLURM_PROCID"])
        logger.addFilter(lambda record: rank == 0)
    format_str = "[%(asctime)s][%(levelname)8s] %(message)s"
    formatter = logging.Formatter(format_str)
    ch.setFormatter(formatter)
    logger.addHandler(ch)
    return logger


def load_config(path):
    import yaml
    cfg = yaml.load(open(path, "r"), Loader=yaml.Loader)
    if "data_root" in cfg:
        original = cfg["data_root"]
        data_root_env = os.environ.get("DATA_ROOT", "")
        if original.startswith("${DATA_ROOT}") and not data_root_env:
            repo_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
            city = original.replace("${DATA_ROOT}/", "").replace("${DATA_ROOT}", "")
            cfg["data_root"] = os.path.join(repo_root, "data_pipeline", city)
        else:
            cfg["data_root"] = os.path.expandvars(original)
    return cfg
